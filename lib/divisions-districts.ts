const districtEnglishByBengali = new Map<string, string>();
for (const division of Object.keys(DISTRICTS_BY_DIVISION)) {
  DISTRICTS_BY_DIVISION[division].forEach((name, index) => {
    districtEnglishByBengali.set(name, DISTRICT_ENGLISH[division]?.[index] ?? name);
  });
}

export function districtLabel(name: string, lang: "bn" | "en") {
  if (lang === "bn") return name;
  return districtEnglishByBengali.get(name) ?? name;
}